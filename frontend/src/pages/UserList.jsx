// Main App Component
export default function UserList() {
  const [users, setUsers] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);
  const [searchTerm, setSearchTerm] = useState("");
  const [sortOrder, setSortOrder] = useState("asc");
  const [selectedUser, setSelectedUser] = useState(null);
  const [isModalOpen, setIsModalOpen] = useState(false);
  const [showBackToTop, setShowBackToTop] = useState(false);
  const scrollContainerRef = useRef(null);
  const scrollTimeoutRef = useRef(null);

  // Sort options configuration
  const sortOptions = [
    { value: "asc", label: "Name (A-Z)" },
    { value: "desc", label: "Name (Z-A)" },
  ];

  // Fetch users on component mount
  useEffect(() => {
    const fetchUsers = async () => {
      try {
        setLoading(true);
        const response = await fetch(
          "https://jsonplaceholder.typicode.com/users"
        );

        if (!response.ok) {
          throw new Error(`HTTP error! status: ${response.status}`);
        }

        const data = await response.json();
        // setUsers(mockUsers);
        setUsers(data);
        setError(null);
      } catch (err) {
        if (process.env.NODE_ENV !== "test") {
          console.error("Error fetching users:", err);
        }
        // console.error("Error fetching users:", err);
        setError(err.message);
      } finally {
        setLoading(false);
      }
    };

    fetchUsers();
  }, []);

  // Filter and sort users
  const filteredAndSortedUsers = users
    .filter((user) => {
      // Regular case-sensitive filter - checks if name contains search term
      return user.name.includes(searchTerm);
    })
    .sort((a, b) => {
      const nameA = a.name.toLowerCase();
      const nameB = b.name.toLowerCase();

      if (sortOrder === "asc") {
        return nameA.localeCompare(nameB);
      } else {
        return nameB.localeCompare(nameA);
      }
    });

  // Handle user card click
  const handleUserClick = (user) => {
    setSelectedUser(user);
    setIsModalOpen(true);
  };

  const handleCloseModal = () => {
    setIsModalOpen(false);
    setSelectedUser(null);
  };

  // Handle scroll for back to top button
  const handleScroll = () => {
    if (scrollTimeoutRef.current) {
      clearTimeout(scrollTimeoutRef.current);
    }

    scrollTimeoutRef.current = setTimeout(() => {
      if (scrollContainerRef.current) {
        const scrollTop = scrollContainerRef.current.scrollTop;
        // console.log("Scroll position:", scrollTop); // Debug log
        // Show button when scrolled more than 100px
        setShowBackToTop(scrollTop > 100);
      }
    }, 10); // Very short delay to batch scroll events
  };

  // Scroll to top function
  const scrollToTop = () => {
    if (scrollContainerRef.current) {
      scrollContainerRef.current.scrollTo({
        top: 0,
        behavior: "smooth",
      });
    }
  };

  // Loading state
  if (loading) {
    return (
      <div className="min-h-screen bg-gray-50 flex items-center justify-center">
        <div className="text-center">
          <div className="animate-spin rounded-full h-12 w-12 border-b-2 border-blue-600 mx-auto mb-4"></div>
          <p className="text-gray-600 text-lg">Loading users...</p>
        </div>
      </div>
    );
  }

  // Error state
  if (error) {
    return (
      <div className="min-h-screen bg-gray-50 flex items-center justify-center text-center">
        <div className="bg-red-50 border border-red-200 rounded-lg p-6 max-w-md mx-4">
          <div className="flex items-center mb-4 justify-center">
            <ErrorIcon className="h-8 w-8 text-red-600 mr-3" />
            <h3 className="text-lg font-semibold text-red-800">
              Error Loading Users
            </h3>
          </div>
          <p className="text-red-700 mb-4">{error}</p>
          <button
            onClick={() => window.location.reload()}
            className="bg-red-600 hover:bg-red-700 text-white px-4 py-2 rounded-lg transition duration-200"
          >
            Try Again
          </button>
        </div>
      </div>
    );
  }

  return (
    <div className="h-screen overflow-hidden flex flex-col">
      <div className=" mx-auto p-4 sm:p-6 lg:p-14 overflow-hidden flex-1 flex flex-col min-h-0 w-full">
        {/* Header */}
        <div className="mb-4 text-center flex-shrink-0">
          <h1 className="text-3xl sm:text-4xl font-bold text-gray-900 mb-2">
            User Directory
          </h1>
          <p className="text-gray-600 text-lg">
            Browse and search through our user database
          </p>
        </div>

        {/* Search and Sort */}
        <div className="flex flex-col mb-4">
          <div className="mb-2 sm:w-[33vw]">
            <SearchInput
              searchTerm={searchTerm}
              onSearchChange={setSearchTerm}
              placeholder="Search users by name..."
            />
          </div>

          {/* Results Info */}
          <div className=" flex justify-between items-end flex-shrink-0">
            <p className="text-sm text-gray-600 whitespace-nowrap truncate mt-4">
              Showing {filteredAndSortedUsers.length} of {users.length} users
              {searchTerm && <span> matching "{searchTerm}"</span>}
            </p>
            <SortDropdown
              sortOrder={sortOrder}
              onSortChange={setSortOrder}
              options={sortOptions}
            />
          </div>
        </div>

        {/* Users Grid - Fixed scroll container */}
        <div
          ref={scrollContainerRef}
          onScroll={handleScroll}
          className="flex-1 min-h-0 border-2 rounded-xl overflow-auto scrollbar-thumb-only overflow-x-hidden bg-blue-100 outline-none"
        >
          {filteredAndSortedUsers.length > 0 ? (
            <div className="grid grid-cols-1 sm:grid-cols-2 xl:grid-cols-3 gap-4 p-4 xl:gap-6 xl:p-6">
              {filteredAndSortedUsers.map((user) => (
                <UserCard key={user.id} user={user} onClick={handleUserClick} />
              ))}
            </div>
          ) : (
            <div className="flex items-center justify-center min-h-full p-8">
              <div className="text-center max-w-md">
                <h3 className="text-lg font-medium text-gray-900 mb-2">
                  No users found
                </h3>
                <p className="text-gray-600">
                  {searchTerm
                    ? `No users match "${searchTerm}". Try a different search term.`
                    : "No users available at the moment."}
                </p>
                {searchTerm && (
                  <button
                    onClick={() => setSearchTerm("")}
                    className="mt-4 text-blue-600 hover:text-blue-700 font-medium"
                  >
                    Clear search
                  </button>
                )}
              </div>
            </div>
          )}
        </div>

        {/* Back to Top Button - Shows on all screen sizes when scrolled */}
        {showBackToTop && (
          <button
            onClick={scrollToTop}
            className="fixed bottom-4 right-4 bg-blue-600 hover:bg-blue-700 text-white p-3 rounded-full shadow-lg transition-all duration-300 z-50"
            aria-label="Back to top"
          >
            <UpArrow className="w-5 h-5 " />
          </button>
        )}

        {/* User Details Modal */}
        <UserModal
          user={selectedUser}
          isOpen={isModalOpen}
          onClose={handleCloseModal}
        />
      </div>
    </div>
  );
}
